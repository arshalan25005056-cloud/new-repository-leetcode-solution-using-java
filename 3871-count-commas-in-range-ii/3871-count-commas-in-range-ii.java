class Solution {
    public long countCommas(long n) {
        if (n < 1000) {
            return 0;
        }

        long res = 0;

        if (n < 1_000_000) {
            res = n - 1000 + 1;
        } 
        else if (n < 1_000_000_000) {
            res = (1_000_000 - 1000)
                + (n - 1_000_000 + 1) * 2;
        } 
        else if (n < 1_000_000_000_000L) {
            res = (1_000_000 - 1000)
                + (1_000_000_000 - 1_000_000) * 2
                + (n - 1_000_000_000 + 1) * 3;
        } 
        else if (n < 1_000_000_000_000_000L) {
            res = (1_000_000 - 1000)
                + (1_000_000_000 - 1_000_000) * 2
                + (1_000_000_000_000L - 1_000_000_000L) * 3
                + (n - 1_000_000_000_000L + 1) * 4;
        } 
        else {
            res = (1_000_000 - 1000)
                + (1_000_000_000 - 1_000_000) * 2
                + (1_000_000_000_000L - 1_000_000_000L) * 3
                + (1_000_000_000_000_000L - 1_000_000_000_000L) * 4
                + (n - 1_000_000_000_000_000L + 1) * 5;
        }

        return res;
    }
}